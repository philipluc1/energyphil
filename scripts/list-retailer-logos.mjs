#!/usr/bin/env node
// Lists the retailer logo files in public/images/retailers and writes
// lib/retailerLogos.generated.ts, so the site shows a logo only where a file
// exists (no broken images). Runs automatically before `npm run dev` and
// `npm run build`; run by hand with: node scripts/list-retailer-logos.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DIR = path.join(ROOT, "public", "images", "retailers");
const OUT = path.join(ROOT, "lib", "retailerLogos.generated.ts");

const files = fs.existsSync(DIR) ? fs.readdirSync(DIR).filter((f) => /\.(png|svg|webp|jpg|jpeg)$/i.test(f)).sort() : [];
// One entry per retailer slug; prefer SVG, then PNG, WebP, JPG.
const rank = (f) => ["svg", "png", "webp", "jpg", "jpeg"].indexOf(f.split(".").pop().toLowerCase());
const bySlug = {};
for (const f of files) {
  const slug = f.replace(/\.[^.]+$/, "").toLowerCase();
  if (!bySlug[slug] || rank(f) < rank(bySlug[slug])) bySlug[slug] = f;
}
const body = Object.entries(bySlug).map(([slug, f]) => `  ${JSON.stringify(slug)}: "/images/retailers/${f}",`).join("\n");
fs.writeFileSync(
  OUT,
  `// GENERATED by scripts/list-retailer-logos.mjs. Do not edit by hand.\n// Retailer slug -> logo file in public/images/retailers.\n\nexport const RETAILER_LOGO_FILES: Record<string, string> = {\n${body}${body ? "\n" : ""}};\n`,
);
console.log(`Retailer logos: ${Object.keys(bySlug).length} found`);
