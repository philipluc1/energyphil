#!/usr/bin/env node
// Lists the retailer logo files in public/images/retailers and writes
// lib/retailerLogos.generated.ts (file and width:height ratio per retailer),
// so the site shows a logo only where a file exists and can size the tile
// to fit a wide wordmark. Runs automatically before `npm run dev` and
// `npm run build`; run by hand with: node scripts/list-retailer-logos.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DIR = path.join(ROOT, "public", "images", "retailers");
const OUT = path.join(ROOT, "lib", "retailerLogos.generated.ts");

const files = fs.existsSync(DIR) ? fs.readdirSync(DIR).filter((f) => /\.(png|svg|webp|jpg|jpeg)$/i.test(f)).sort() : [];
// One entry per retailer slug; prefer SVG, then PNG, WebP, JPG.
const rank = (f) => ["svg", "png", "webp", "jpg", "jpeg"].indexOf(f.split(".").pop().toLowerCase());
const bySlug = {};
for (const f of files) {
  const slug = f.replace(/\.[^.]+$/, "").toLowerCase();
  if (!bySlug[slug] || rank(f) < rank(bySlug[slug])) bySlug[slug] = f;
}

/** width / height of an image file, from its header (PNG, JPEG, SVG viewBox); 1 if unknown. */
function ratioOf(file) {
  const buf = fs.readFileSync(path.join(DIR, file));
  try {
    if (buf.slice(1, 4).toString() === "PNG") return buf.readUInt32BE(16) / buf.readUInt32BE(20);
    if (buf[0] === 0xff && buf[1] === 0xd8) {
      let i = 2;
      while (i < buf.length) {
        if (buf[i] !== 0xff) break;
        const marker = buf[i + 1];
        const len = buf.readUInt16BE(i + 2);
        if (marker >= 0xc0 && marker <= 0xcf && marker !== 0xc4 && marker !== 0xc8 && marker !== 0xcc) return buf.readUInt16BE(i + 7) / buf.readUInt16BE(i + 5);
        i += 2 + len;
      }
    }
    if (/\.svg$/i.test(file)) {
      const t = buf.toString("utf8");
      const vb = /viewBox=["']\s*[-\d.]+[\s,]+[-\d.]+[\s,]+([\d.]+)[\s,]+([\d.]+)/i.exec(t);
      if (vb) return parseFloat(vb[1]) / parseFloat(vb[2]);
      const w = /\swidth=["']([\d.]+)/i.exec(t), h = /\sheight=["']([\d.]+)/i.exec(t);
      if (w && h) return parseFloat(w[1]) / parseFloat(h[1]);
    }
  } catch { /* fall through */ }
  return 1;
}

const body = Object.entries(bySlug).map(([slug, f]) => `  ${JSON.stringify(slug)}: { file: "/images/retailers/${f}", ratio: ${Math.round(ratioOf(f) * 100) / 100} },`).join("\n");
fs.writeFileSync(
  OUT,
  `// GENERATED by scripts/list-retailer-logos.mjs. Do not edit by hand.\n// Retailer slug -> logo file in public/images/retailers, and its width:height.\n\nexport const RETAILER_LOGO_FILES: Record<string, { file: string; ratio: number }> = {\n${body}${body ? "\n" : ""}};\n`,
);
console.log(`Retailer logos: ${Object.keys(bySlug).length} found`);
