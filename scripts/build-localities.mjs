#!/usr/bin/env node
// Builds lib/vicLocalities.ts: every Victorian suburb (delivery area) and its
// postcode, used on /check to stop a postcode that doesn't match the suburb.
//
// Usage:  node scripts/build-localities.mjs <source.csv>
//
// The CSV needs columns `postcode`, `locality` and `state`; an optional `type`
// column is used to keep only "Delivery Area" rows (PO Box and large-volume
// receiver postcodes aren't street addresses, so a home can't be in one).
//
// Source used for the current file: the community-maintained
// matthewproctor/australianpostcodes list on GitHub (no licence stated).
// Before launch, regenerate from an openly licensed source, e.g. the ABS
// Suburbs and Localities (SAL) 2021 to Postal Areas (POA) 2021 list on
// data.gov.au (CC BY), saved as CSV with those three column names.

import { readFileSync, writeFileSync } from "node:fs";

const src = process.argv[2];
if (!src) {
  console.error("Usage: node scripts/build-localities.mjs <source.csv>");
  process.exit(1);
}

/** Minimal CSV parser: quoted fields, commas and doubled quotes. */
function parseCsv(text) {
  const rows = [];
  let row = [], field = "", q = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (c === '"') q = false;
      else field += c;
    } else if (c === '"') q = true;
    else if (c === ",") { row.push(field); field = ""; }
    else if (c === "\n" || c === "\r") {
      if (c === "\r" && text[i + 1] === "\n") i++;
      row.push(field); rows.push(row); row = []; field = "";
    } else field += c;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  return rows.filter((r) => r.length > 1);
}

/** "ALTONA NORTH" -> "Altona North", "MCKINNON" -> "McKinnon". */
export function titleCase(s) {
  return s
    .toLowerCase()
    .replace(/(^|[\s\-'(])([a-z])/g, (_, a, b) => a + b.toUpperCase())
    .replace(/\bMc([a-z])/g, (_, b) => "Mc" + b.toUpperCase())
    .replace(/\bRaaf\b/g, "RAAF");
}

const [head, ...body] = parseCsv(readFileSync(src, "utf8"));
const col = (n) => head.indexOf(n);
const [iPc, iLoc, iState, iType] = [col("postcode"), col("locality"), col("state"), col("type")];
if (iPc < 0 || iLoc < 0 || iState < 0) {
  console.error("CSV needs postcode, locality and state columns");
  process.exit(1);
}

const byPostcode = {};
for (const r of body) {
  if (r[iState] !== "VIC") continue;
  if (iType >= 0 && r[iType] && r[iType] !== "Delivery Area") continue;
  const pc = r[iPc].padStart(4, "0");
  if (!/^3\d{3}$/.test(pc)) continue; // street-address postcodes in Victoria are 3xxx
  const name = titleCase(r[iLoc].trim());
  if (/ (Mc|Dc)$/.test(name)) continue; // mail and delivery centres, not suburbs
  (byPostcode[pc] ??= new Set()).add(name);
}

const keys = Object.keys(byPostcode).sort();
const lines = keys.map((pc) => `  "${pc}": ${JSON.stringify([...byPostcode[pc]].sort().join("|"))},`);
const count = keys.reduce((n, k) => n + byPostcode[k].size, 0);

writeFileSync(
  new URL("../lib/vicLocalities.ts", import.meta.url),
  `// GENERATED by scripts/build-localities.mjs. Do not edit by hand.
// Victorian street-address postcodes and the suburbs in each (${keys.length} postcodes, ${count} suburbs).
// Suburbs are joined with "|". Loaded on demand by the check page.

export const VIC_LOCALITIES: Record<string, string> = {
${lines.join("\n")}
};
`,
);
console.log(`Wrote lib/vicLocalities.ts: ${keys.length} postcodes, ${count} suburbs`);
